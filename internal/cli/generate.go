// Marker halves of the generated-file header (render.go), matched
// version-agnostically so output written by an older gqlc release
// passes the tripwire sweep (CLI-1 spec §5.1 step 3).
const (
	markerPrefix = "// Code generated by gqlc "
	markerSuffix = " DO NOT EDIT."
)

// newGenerateCmd builds the generate command: the full config-driven
// pipeline (CLI-1 spec). SilenceUsage is set per-run in RunE so flag
// and Args parse errors keep the usage dump while runtime failures
// print diagnostics only (§2.2).
func newGenerateCmd() *cobra.Command {
	var cfgPath string
	cmd := &cobra.Command{
		Use:   "generate",
		Short: "Generate Go code from the schema and queries the config file declares",
		Long: `generate runs the pipeline the config file declares: parse the schema,
parse and resolve every named query in the query directory, and write
the generated Go package to the output directory.

The output directory belongs to gqlc alone: each run replaces its
contents, and a run aborts — deleting nothing — if the directory holds
anything gqlc cannot prove it generated.

Relative paths in the config file are relative to the config file's
directory, not the working directory.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			cmd.SilenceUsage = true
			return runGenerate(cmd, cfgPath)
		},
	}
	cmd.Flags().StringVarP(&cfgPath, "file", "f", config.DefaultFilename,
		"path to the config file")
	return cmd
}

// runGenerate is the CLI adapter around pipeline.Run: it delegates
// stages 1-8 of the pipeline (spec §3.1) to internal/cli/pipeline,
// prints accumulated diagnostics, forms the summary error, and — on
// success — invokes the ADR 0012 tripwire-guarded write. The
// three-way pipeline.Result contract (see pipeline.Run doc) drives
// the three branches below.
func runGenerate(cmd *cobra.Command, cfgPath string) error {
	res, err := pipeline.Run(cfgPath)
	if err != nil {
		// Missing config file: keep the sibling-subcommand hint
		// CLI-side. The pipeline is subcommand-agnostic; the sentinel
		// is how the CLI keys off that specific stage-1 case (spec
		// §2.3).
		if errors.Is(err, pipeline.ErrConfigMissing) {
			return missingConfig(cfgPath)
		}
		return err
	}

	// Stage-7 accumulation: nil error + populated Diagnostics. Print
	// every line to stderr in pipeline order, then return the
	// singular/plural summary (spec §2.3). Files is nil in this
	// branch; nothing is written.
	if len(res.Diagnostics) > 0 {
		for _, d := range res.Diagnostics {
			if _, werr := fmt.Fprintln(cmd.ErrOrStderr(), d); werr != nil {
				return werr
			}
		}
		noun := "errors"
		if len(res.Diagnostics) == 1 {
			noun = "error"
		}
		return fmt.Errorf("generate: %d %s", len(res.Diagnostics), noun)
	}

	// Success: write every target's output under the ADR 0012 protocol
	// (spec §5) in two phases (config-multi-target §7). The pipeline
	// resolved each OutDir at stage 2 (spec §3.1) — the CLI takes them
	// verbatim rather than re-loading the config.
	plans, err := inspectOutputs(res.Targets)
	if err != nil {
		return err
	}
	return commitOutputs(res.Targets, plans)
}

// missingConfig renders the absent-config-file message (CLI-2 §6.1).
// Shared with init.go: `init --add` has nothing to append to and
// reports the same words, so the hint stays one string rather than two
// that drift (config-multi-target §8.2).
func missingConfig(cfgPath string) error {
	return fmt.Errorf("no config file at %s (run gqlc init to create one)", cfgPath)
}

// resolvePath joins a config-file-relative path against the config
// file's directory (CLI-1 spec §3.1 stage 2); absolute paths pass
// through unchanged. Shared with init.go (warning-line path checks);
// pipeline.Run has its own internal copy for stage 2.
func resolvePath(baseDir, p string) string {
	if filepath.IsAbs(p) {
		return p
	}
	return filepath.Join(baseDir, p)
}

// targetPlan is phase A's finding for one target
// (config-multi-target §7). Producing it mutates nothing, and phase B
// deletes nothing a plan does not authorise.
type targetPlan struct {
	dir    string   // the target's resolved OutDir
	create bool     // dir is absent; phase B must create it
	wipe   []string // basenames phase A proved marked — the only
	// entries phase B is permitted to remove
}

// inspectOutputs runs §7.1 for every target and returns one plan per
// target, index-parallel to targets. It performs no filesystem
// mutation. A non-nil error means no plan is returned and nothing has
// been touched.
//
// Targets are inspected in order and the first failure aborts, so the
// entry named in the error is the earliest failing one — user-visible
// whenever two targets would both trip the wire.
func inspectOutputs(targets []pipeline.TargetResult) ([]targetPlan, error) {
	plans := make([]targetPlan, 0, len(targets))
	for i, t := range targets {
		plan, err := inspectOutput(t.OutDir)
		if err != nil {
			return nil, fmt.Errorf("graph[%d]: %w", i, err)
		}
		plans = append(plans, plan)
	}
	return plans, nil
}

// inspectOutput is the §5.1 tripwire algorithm's read-only half, steps
// 1-5 of §7.1, for one target's output directory.
func inspectOutput(dir string) (targetPlan, error) {
	// Step 1 — stat. An absent directory is phase B's to create; a
	// non-directory is the abort ADR 0012 names.
	info, err := os.Stat(dir)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return targetPlan{dir: dir, create: true}, nil
	case err != nil:
		return targetPlan{}, fmt.Errorf("output: %w", err)
	case !info.IsDir():
		return targetPlan{}, fmt.Errorf("output: %s is not a directory", dir)
	}

	// Step 2 — read.
	entries, err := os.ReadDir(dir)
	if err != nil {
		return targetPlan{}, fmt.Errorf("output: %w", err)
	}

	// Step 3 — sweep every entry, collecting every offender, not the
	// first (ADR 0012: the abort names them all). A read failure
	// aborts: the directory's state cannot be proven, so nothing is
	// touched.
	var offenders, wipe []string
	for _, e := range entries {
		if e.IsDir() {
			offenders = append(offenders, e.Name()+"/")
			continue
		}
		if !e.Type().IsRegular() {
			offenders = append(offenders, e.Name())
			continue
		}
		marked, err := markedFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return targetPlan{}, fmt.Errorf("output: %w", err)
		}
		if !marked {
			offenders = append(offenders, e.Name())
			continue
		}
		wipe = append(wipe, e.Name())
	}

	// Step 4 — offenders present → abort (§5.3). Nothing is deleted.
	if len(offenders) > 0 {
		return targetPlan{}, fmt.Errorf("output directory %s contains entries not generated by gqlc: %s; move or delete them and re-run",
			dir, strings.Join(offenders, ", "))
	}

	// Step 5 — record the swept entries as this target's wipe list.
	return targetPlan{dir: dir, wipe: wipe}, nil
}

// commitOutputs runs §7.2 against plans from inspectOutputs, in target
// order — target i's directory is rewritten before target i+1's, so an
// I/O error at i leaves the targets before it already rewritten (§7.3).
//
// Every step here is a mutation, and every one of them runs after the
// last inspection: an abort under the tripwire — for any target —
// reaches this function not at all.
func commitOutputs(targets []pipeline.TargetResult, plans []targetPlan) error {
	for i, t := range targets {
		if err := commitOutput(plans[i], t.Files); err != nil {
			return fmt.Errorf("graph[%d]: %w", i, err)
		}
	}
	return nil
}

// commitOutput runs §7.2 steps 6-8 for one target. Wipe and write are
// interleaved per target rather than wiping every target and then
// writing every target, so each directory spends the shortest possible
// time empty.
func commitOutput(plan targetPlan, files []codegen.File) error {
	// Step 6 — create.
	if plan.create {
		if err := os.MkdirAll(plan.dir, 0o755); err != nil {
			return fmt.Errorf("output: %w", err)
		}
	}

	// Step 7 — wipe exactly the entries phase A proved marked, never a
	// superset. An entry already gone satisfies the wipe: the §4.3
	// overlap check has limits that let two targets hold overlapping
	// wipe lists, and an intolerant Remove would then abort mid-commit
	// over a file whose absence is the outcome it wanted.
	for _, name := range plan.wipe {
		if err := os.Remove(filepath.Join(plan.dir, name)); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return fmt.Errorf("output: %w", err)
		}
	}

	// Step 8 — each File lands at its Path in slice order; Generate's
	// contract sorts the slice by Path, so write order is
	// deterministic too.
	for _, f := range files {
		if err := os.WriteFile(filepath.Join(plan.dir, f.Path), f.Contents, 0o644); err != nil {
			return fmt.Errorf("output: %w", err)
		}
	}
	return nil
}

// markedFile reports whether the file's first line — the bytes before
// the first LF; a file without an LF is its own first line — starts
// with markerPrefix and ends with markerSuffix. Version-agnostic in
// the middle: checking against the current version.Version would make
// every gqlc upgrade brick its own output directory (§5.1).
func markedFile(path string) (bool, error) {
	contents, err := os.ReadFile(path)
	if err != nil {
		return false, err
	}
	line, _, _ := bytes.Cut(contents, []byte("\n"))
	return bytes.HasPrefix(line, []byte(markerPrefix)) && bytes.HasSuffix(line, []byte(markerSuffix)), nil
}
