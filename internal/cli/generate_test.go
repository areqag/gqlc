// TestGenerateMultiTarget: every target the config declares is
// generated, into its own directory, with its own package clause and
// driver import; a second run is byte-identical (§12.1).
func TestGenerateMultiTarget(t *testing.T) {
	dir := writeTwoTargetProject(t)
	stdout, stderr, err := runGenerateIn(t, dir)
	require.NoError(t, err, "stderr: %s", stderr)
	require.Empty(t, stdout)
	require.Empty(t, stderr)

	out, out2 := filepath.Join(dir, "out"), filepath.Join(dir, "out2")
	require.Equal(t, []string{"db.go", "models.go", "people.cypher.go", "querier.go"}, listDir(t, out))
	require.Equal(t, []string{"db.go", "invoices.cypher.go", "models.go", "querier.go"}, listDir(t, out2))
	for _, name := range listDir(t, out2) {
		requireMarkerHeaded(t, filepath.Join(out2, name))
	}

	db, err := os.ReadFile(filepath.Join(out2, "db.go"))
	require.NoError(t, err)
	require.Contains(t, string(db), "\npackage invoicedb\n")
	require.Contains(t, string(db), `"github.com/neo4j/neo4j-go-driver/v6/neo4j"`)

	first, first2 := snapshotDir(t, out), snapshotDir(t, out2)
	_, _, err = runGenerateIn(t, dir)
	require.NoError(t, err)
	require.Equal(t, first, snapshotDir(t, out))
	require.Equal(t, first2, snapshotDir(t, out2))
}

// TestGenerateAbortsBeforeAnyWrite: the tripwire fires on entry 1's
